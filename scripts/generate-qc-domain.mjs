import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const domain = JSON.parse(await readFile(resolve(root, "contracts/qc-domain.v1.json"), "utf8"));
const colors = JSON.parse(await readFile(resolve(root, "packages/typescript/qc-theme/src/colors.json"), "utf8"));
const { limits, inputRoutes, outputRoutes } = domain;
const sceneColors = colors.scene;
const tsRoutes = (routes) => routes.map(({ id, label, group }) => `  { id: ${id}, label: ${JSON.stringify(label)}, group: ${JSON.stringify(group)} }`).join(",\n");
const pyRoutes = (routes) => `{${routes.map(({ id, label }) => `${id}: ${JSON.stringify(label)}`).join(", ")}}`;
const rustRoutes = (routes) => routes.map(({ id, label }) => `    (${id}, ${JSON.stringify(label)}),`).join("\n");
const rustName = (name) => name.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toUpperCase();
const rustVisualColors = Object.entries({ ...colors.category, ...colors.hardware }).map(([name, value]) => `    pub const ${rustName(name)}: &str = ${JSON.stringify(value)};`).join("\n");

const typescript = `// Generated by scripts/generate-qc-domain.mjs. Do not edit by hand.
export const QC_GRID_ROWS = ${limits.gridRows};
export const QC_GRID_COLUMNS = ${limits.gridColumns};
export const QC_SCENE_COUNT = ${limits.scenes};
export const QC_MINIMUM_TEMPO_BPM = ${limits.minimumTempoBpm};
export const QC_MAXIMUM_TEMPO_BPM = ${limits.maximumTempoBpm};
export const QC_IPC_MAX_FRAME_BYTES = ${limits.ipcMaxFrameBytes};
export const QC_STATE_EVENT_DEFAULT_LIMIT = ${limits.stateEventDefaultLimit};
export const QC_STATE_EVENT_MAXIMUM_LIMIT = ${limits.stateEventMaximumLimit};
export const QC_SCENE_COLORS = ${JSON.stringify(sceneColors)} as const;
export const QC_CATEGORY_COLORS = ${JSON.stringify(colors.category)} as const;
export const QC_HARDWARE_COLORS = ${JSON.stringify(colors.hardware)} as const;
export const QC_INPUT_ROUTES = [
${tsRoutes(inputRoutes)}
] as const;
export const QC_OUTPUT_ROUTES = [
${tsRoutes(outputRoutes)}
] as const;
`;

const python = `# Generated by scripts/generate-qc-domain.mjs. Do not edit by hand.
GRID_ROWS = ${limits.gridRows}
GRID_COLUMNS = ${limits.gridColumns}
SCENE_COUNT = ${limits.scenes}
MINIMUM_TEMPO_BPM = ${limits.minimumTempoBpm}
MAXIMUM_TEMPO_BPM = ${limits.maximumTempoBpm}
IPC_MAX_FRAME_BYTES = ${limits.ipcMaxFrameBytes}
STATE_EVENT_DEFAULT_LIMIT = ${limits.stateEventDefaultLimit}
STATE_EVENT_MAXIMUM_LIMIT = ${limits.stateEventMaximumLimit}
SCENE_COLORS = ${JSON.stringify(sceneColors)}
CATEGORY_COLORS = ${JSON.stringify(colors.category)}
HARDWARE_COLORS = ${JSON.stringify(colors.hardware)}
INPUT_ROUTE_LABELS = ${pyRoutes(inputRoutes)}
OUTPUT_ROUTE_LABELS = ${pyRoutes(outputRoutes)}
`;

const rust = `// Generated by scripts/generate-qc-domain.mjs. Do not edit by hand.
pub const GRID_ROWS: u32 = ${limits.gridRows};
pub const GRID_COLUMNS: u32 = ${limits.gridColumns};
pub const SCENE_COUNT: u32 = ${limits.scenes};
pub const MINIMUM_TEMPO_BPM: u32 = ${limits.minimumTempoBpm};
pub const MAXIMUM_TEMPO_BPM: u32 = ${limits.maximumTempoBpm};
pub const IPC_MAX_FRAME_BYTES: usize = ${limits.ipcMaxFrameBytes};
pub const STATE_EVENT_DEFAULT_LIMIT: usize = ${limits.stateEventDefaultLimit};
pub const STATE_EVENT_MAXIMUM_LIMIT: usize = ${limits.stateEventMaximumLimit};
pub const SCENE_COLORS: &[&str] = &[
    ${sceneColors.map((value) => JSON.stringify(value)).join(", ")},
];
pub mod visual_colors {
${rustVisualColors}
}
pub const INPUT_ROUTES: &[(u32, &str)] = &[
${rustRoutes(inputRoutes)}
];
pub const OUTPUT_ROUTES: &[(u32, &str)] = &[
${rustRoutes(outputRoutes)}
];
`;

const java = `// Generated by scripts/generate-qc-domain.mjs. Do not edit by hand.
package com.qccontrol.mobile;

final class QcDomain {
    static final int GRID_ROWS = ${limits.gridRows};
    static final int GRID_COLUMNS = ${limits.gridColumns};
    static final int SCENE_COUNT = ${limits.scenes};
    static final int MINIMUM_TEMPO_BPM = ${limits.minimumTempoBpm};
    static final int MAXIMUM_TEMPO_BPM = ${limits.maximumTempoBpm};
    static final int IPC_MAX_FRAME_BYTES = ${limits.ipcMaxFrameBytes};
    static final int STATE_EVENT_DEFAULT_LIMIT = ${limits.stateEventDefaultLimit};
    static final int STATE_EVENT_MAXIMUM_LIMIT = ${limits.stateEventMaximumLimit};
    private QcDomain() {}
}
`;

const outputs = [
  [resolve(root, "packages/typescript/qc-client/src/generated-domain.ts"), typescript],
  [resolve(root, "services/device-gateway/src/qc_device_gateway/domain.py"), python],
  [resolve(root, "packages/python/qc-gateway-client/src/qc_gateway_client/generated_domain.py"), python],
  [resolve(root, "services/mcp-server/src/qc_mcp_server/generated_domain.py"), python],
  [resolve(root, "packages/rust/qc-protocol/src/domain.rs"), rust],
  [resolve(root, "apps/android/android/app/src/main/java/com/qccontrol/mobile/QcDomain.java"), java]
];

let stale = false;
for (const [path, content] of outputs) {
  if (process.argv.includes("--check")) {
    const current = await readFile(path, "utf8").catch(() => "");
    if (current.replaceAll("\r\n", "\n") !== content) {
      console.error(`${path} is not generated from contracts/qc-domain.v1.json`);
      stale = true;
    }
  } else {
    await writeFile(path, content);
  }
}
if (stale) process.exitCode = 1;
