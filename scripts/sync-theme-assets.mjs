import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const check = process.argv.includes("--check");
const visualAssets = JSON.parse(await readFile(resolve(root, "packages/typescript/qc-theme/src/assets.json"), "utf8"));
const assetCopies = Object.values(visualAssets).map(({ sourcePath, deployedPaths }) => [sourcePath, deployedPaths]);
const nativeTheme = JSON.parse(await readFile(resolve(root, "packages/typescript/qc-theme/src/native-theme.json"), "utf8"));
const brand = JSON.parse(await readFile(resolve(root, "packages/typescript/qc-theme/src/brand.json"), "utf8"));
const upper = (value) => value.toUpperCase();
const generatedText = [
  ["apps/android/android/app/src/main/res/values/colors.xml", `<?xml version="1.0" encoding="utf-8"?>
<resources>
    <!-- Generated by scripts/sync-theme-assets.mjs from @ndsp-qc/theme. -->
    <color name="colorPrimary">${upper(nativeTheme.android.primary)}</color>
    <color name="colorPrimaryDark">${upper(nativeTheme.android.background)}</color>
    <color name="colorAccent">${upper(nativeTheme.android.accent)}</color>
    <color name="brandBackground">${upper(nativeTheme.android.background)}</color>
    <color name="brandScreen">${upper(nativeTheme.android.brandScreen)}</color>
</resources>
`],
  ["apps/android/android/app/src/main/res/values/ic_launcher_background.xml", `<?xml version="1.0" encoding="utf-8"?>
<resources>
    <!-- Generated by scripts/sync-theme-assets.mjs from @ndsp-qc/theme. -->
    <color name="ic_launcher_background">${upper(nativeTheme.android.launcherBackground)}</color>
</resources>
`],
  ["apps/android/android/app/src/main/res/values/strings.xml", `<?xml version="1.0" encoding="utf-8"?>
<resources>
    <!-- Generated by scripts/sync-theme-assets.mjs from @ndsp-qc/theme. -->
    <string name="app_name">${brand.appName}</string>
    <string name="title_activity_main">${brand.appName}</string>
    <string name="device_name">${brand.deviceName}</string>
    <string name="download_folder">${brand.appName}</string>
    <string name="relay_notification_title">${brand.appName} relay</string>
    <string name="app_font_family">${nativeTheme.android.appFontFamily}</string>
    <string name="package_name">${brand.androidPackage}</string>
    <string name="custom_url_scheme">${brand.androidPackage}</string>
</resources>
`]
];

const brandedJson = [
  ["apps/android/capacitor.config.json", () => ({
    appId: brand.androidPackage,
    appName: brand.appName,
    webDir: "dist",
    backgroundColor: nativeTheme.android.background,
    android: {
      allowMixedContent: false,
      backgroundColor: nativeTheme.android.background
    },
    plugins: {
      StatusBar: {
        style: "DARK",
        backgroundColor: nativeTheme.android.background
      }
    }
  })],
  ["apps/windows/src-tauri/tauri.conf.json", (config) => ({
    ...config,
    productName: brand.appName,
    identifier: brand.windowsIdentifier,
    app: { ...config.app, windows: config.app.windows.map((window) => ({ ...window, title: brand.appName })) },
    bundle: {
      ...config.bundle,
      shortDescription: brand.windowsShortDescription,
      longDescription: brand.windowsLongDescription,
      windows: { ...config.bundle.windows, nsis: { ...config.bundle.windows.nsis, startMenuFolder: brand.appName } }
    }
  })]
];

let stale = false;
for (const [source, targets] of assetCopies) {
  const bytes = await readFile(resolve(root, source));
  for (const target of targets) {
    const targetPath = resolve(root, target);
    if (check) {
      const current = await readFile(targetPath).catch(() => Buffer.alloc(0));
      if (!current.equals(bytes)) {
        console.error(`${target} is not synchronized with ${source}`);
        stale = true;
      }
    } else {
      await writeFile(targetPath, bytes);
    }
  }
}
for (const [target, content] of generatedText) {
  const targetPath = resolve(root, target);
  if (check) {
    const current = await readFile(targetPath, "utf8").catch(() => "");
    if (current.replaceAll("\r\n", "\n") !== content) {
      console.error(`${target} is not generated from @ndsp-qc/theme`);
      stale = true;
    }
  } else {
    await writeFile(targetPath, content);
  }
}
for (const [target, transform] of brandedJson) {
  const targetPath = resolve(root, target);
  const current = JSON.parse(await readFile(targetPath, "utf8"));
  const expected = transform(current);
  if (check) {
    if (JSON.stringify(current) !== JSON.stringify(expected)) {
      console.error(`${target} branding is not synchronized with @ndsp-qc/theme`);
      stale = true;
    }
  } else {
    await writeFile(targetPath, `${JSON.stringify(expected, null, 2)}\r\n`);
  }
}
if (stale) process.exitCode = 1;
