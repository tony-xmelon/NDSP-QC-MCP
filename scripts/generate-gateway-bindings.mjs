import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const manifestPath = resolve(root, "contracts/gateway-methods.v1.json");
const schemaPath = resolve(root, "contracts/gateway.v1.schema.json");
const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
const methods = manifest.methods;
const androidDispatchEntries = Object.entries(manifest.androidDispatch ?? {}).flatMap(([kind, names]) => names.map((method) => [method, kind]));
const androidDispatch = new Map(androidDispatchEntries);
if (androidDispatch.size !== methods.length || methods.some((item) => !androidDispatch.has(item.rpc)) || androidDispatchEntries.length !== androidDispatch.size) {
  throw new Error("androidDispatch must classify every gateway method exactly once");
}
const pythonMethods = methods.filter((item) => item.python !== false);
const py = (value) => value === null ? "None" : value === true ? "True" : value === false ? "False" : typeof value === "string" ? JSON.stringify(value) : String(value);
const argName = (arg) => typeof arg === "string" ? arg : arg.name;
const pyArg = (arg) => typeof arg === "string"
  ? `params.get(${JSON.stringify(arg)})`
  : `params.get(${JSON.stringify(arg.name)}, ${py(arg.default)})`;
const rustName = (value) => value.replace(/([a-z0-9])([A-Z])/g, "$1_$2").replace(/[^A-Za-z0-9]+/g, "_").toUpperCase();

const typescript = `// Generated by scripts/generate-gateway-bindings.mjs. Do not edit by hand.
export const GATEWAY_API_VERSION = ${manifest.apiVersion};
export const GATEWAY_CAPABILITIES = ${JSON.stringify(manifest.capabilities)} as const;
export const GATEWAY_METHODS = ${JSON.stringify(methods.map((item) => item.rpc), null, 2)} as const;
export type GatewayRpcMethod = typeof GATEWAY_METHODS[number];
export const GATEWAY_CLIENT_METHODS = {
${methods.map((item) => `  ${JSON.stringify(item.client)}: { rpc: ${JSON.stringify(item.rpc)}, tauri: ${JSON.stringify(item.tauri)}, params: ${JSON.stringify((item.args ?? []).map(argName))} }`).join(",\n")}
} as const;
export type GatewayClientMethod = keyof typeof GATEWAY_CLIENT_METHODS;
export type GatewayClientInvoker = <T>(command: string, args?: Record<string, unknown>) => Promise<T>;

/** Build a typed client from the contract instead of mirroring every native method by hand. */
export function createGatewayClientTransport<TTransport extends object>(invoke: GatewayClientInvoker, target: "tauri" | "rpc" = "tauri"): TTransport {
  return Object.fromEntries(Object.entries(GATEWAY_CLIENT_METHODS).map(([client, descriptor]) => [
    client,
    (...values: unknown[]) => {
      const args = Object.fromEntries(descriptor.params.map((name, index) => [name, values[index]]));
      return invoke(descriptor[target], args);
    }
  ])) as TTransport;
}
`;

const python = `# Generated by scripts/generate-gateway-bindings.mjs. Do not edit by hand.
GATEWAY_API_VERSION = ${manifest.apiVersion}
GATEWAY_CAPABILITIES = ${manifest.pythonCapabilities.map(py).join(", ")},
GATEWAY_METHODS = frozenset((${pythonMethods.map((item) => py(item.rpc)).join(", ")}))

def dispatch_device_method(device, method, params):
${pythonMethods.filter((item) => item.kind !== "system").map((item, index) => `    ${index ? "el" : ""}if method == ${JSON.stringify(item.rpc)}:\n        return device.${item.target}(${(item.args ?? []).map(pyArg).join(", ")})`).join("\n")}
    raise KeyError(method)
`;

const pythonClient = `# Generated by scripts/generate-gateway-bindings.mjs. Do not edit by hand.
GATEWAY_API_VERSION = ${manifest.apiVersion}
GATEWAY_CAPABILITIES = (${manifest.capabilities.map(py).join(", ")})
GATEWAY_METHODS = frozenset((${methods.map((item) => py(item.rpc)).join(", ")}))
`;

const rust = `// Generated by scripts/generate-gateway-bindings.mjs. Do not edit by hand.
#[allow(dead_code)]
pub mod rpc {
${methods.map((item) => `    pub const ${rustName(item.client)}: &str = ${JSON.stringify(item.rpc)};`).join("\n")}
}
`;

const java = `// Generated by scripts/generate-gateway-bindings.mjs. Do not edit by hand.
package com.qccontrol.mobile;

final class GeneratedGatewayMethods {
    private GeneratedGatewayMethods() {}

    static final String[] ALL = {
${methods.map((item) => `        ${JSON.stringify(item.rpc)}`).join(",\n")}
    };

    static boolean contains(String method) {
        for (String candidate : ALL) if (candidate.equals(method)) return true;
        return false;
    }

    static String dispatchKind(String method) {
        switch (method) {
${methods.map((item) => `            case ${JSON.stringify(item.rpc)}: return ${JSON.stringify(androidDispatch.get(item.rpc))};`).join("\n")}
            default: return "UNSUPPORTED";
        }
    }
}
`;

const schema = JSON.parse(await readFile(schemaPath, "utf8"));
schema.$defs.request.properties.method.enum = methods.map((item) => item.rpc);
const schemaOutput = `${JSON.stringify(schema, null, 2)}\n`;
const outputs = [
  [resolve(root, "packages/typescript/qc-client/src/generated-gateway-methods.ts"), typescript],
  [resolve(root, "services/device-gateway/src/qc_device_gateway/generated_gateway_dispatch.py"), python],
  [resolve(root, "packages/python/qc-gateway-client/src/qc_gateway_client/generated_gateway_methods.py"), pythonClient],
  [resolve(root, "apps/windows/src-tauri/src/generated_gateway.rs"), rust],
  [resolve(root, "apps/android/android/app/src/main/java/com/qccontrol/mobile/GeneratedGatewayMethods.java"), java],
  [schemaPath, schemaOutput]
];

let stale = false;
for (const [path, content] of outputs) {
  if (process.argv.includes("--check")) {
    const current = await readFile(path, "utf8").catch(() => "");
    if (current.replaceAll("\r\n", "\n") !== content) {
      console.error(`${path} is not generated from contracts/gateway-methods.v1.json`);
      stale = true;
    }
  } else {
    await writeFile(path, content);
  }
}
if (stale) process.exitCode = 1;
