import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const profile = JSON.parse(await readFile(resolve(root, "contracts/qc-relay-profile.v1.json"), "utf8"));

if (profile.version !== 1 || profile.protocolVersion !== "qc-relay.v1") {
  throw new Error("Unsupported QC relay profile");
}

const rust = `// Generated by scripts/generate-qc-relay-profile.mjs. Do not edit by hand.
pub const PROTOCOL_VERSION: &str = ${JSON.stringify(profile.protocolVersion)};
pub const DEVICE_PAIR_PATH: &str = ${JSON.stringify(profile.devicePairPath)};
pub const DEVICE_CONNECT_PATH: &str = ${JSON.stringify(profile.deviceConnectPath)};
pub const PAIRING_CODE_MINIMUM_LENGTH: usize = ${profile.pairingCodeMinimumLength};
pub const PAIRING_CODE_MAXIMUM_LENGTH: usize = ${profile.pairingCodeMaximumLength};
pub const MINIMUM_CREDENTIAL_LENGTH: usize = ${profile.minimumCredentialLength};
pub const MAX_REQUEST_FRAME_BYTES: usize = ${profile.maxRequestFrameBytes};
pub const MAX_RESULT_FRAME_BYTES: usize = ${profile.maxResultFrameBytes};
pub const COMPLETED_REQUEST_CACHE_SIZE: usize = ${profile.completedRequestCacheSize};
pub const READINESS_INTERVAL_MS: u64 = ${profile.readinessIntervalMs};
pub const MAXIMUM_FAILURE_COUNT: u32 = ${profile.maximumFailureCount};
pub const MAXIMUM_BACKOFF_EXPONENT: u32 = ${profile.maximumBackoffExponent};
pub const MAXIMUM_BACKOFF_SECONDS: u64 = ${profile.maximumBackoffSeconds};
pub const BACKOFF_JITTER_MS: u64 = ${profile.backoffJitterMs};
`;

const java = `// Generated by scripts/generate-qc-relay-profile.mjs. Do not edit by hand.
package com.qccontrol.mobile;

final class GeneratedRelayProfile {
    static final String PROTOCOL_VERSION = ${JSON.stringify(profile.protocolVersion)};
    static final String DEVICE_PAIR_PATH = ${JSON.stringify(profile.devicePairPath)};
    static final String DEVICE_CONNECT_PATH = ${JSON.stringify(profile.deviceConnectPath)};
    static final int PAIRING_CODE_MINIMUM_LENGTH = ${profile.pairingCodeMinimumLength};
    static final int PAIRING_CODE_MAXIMUM_LENGTH = ${profile.pairingCodeMaximumLength};
    static final int MINIMUM_CREDENTIAL_LENGTH = ${profile.minimumCredentialLength};
    static final int MAX_REQUEST_FRAME_BYTES = ${profile.maxRequestFrameBytes};
    static final int MAX_RESULT_FRAME_BYTES = ${profile.maxResultFrameBytes};
    static final int COMPLETED_REQUEST_CACHE_SIZE = ${profile.completedRequestCacheSize};
    static final long READINESS_INTERVAL_MS = ${profile.readinessIntervalMs}L;
    static final long PING_INTERVAL_MS = ${profile.androidPingIntervalMs}L;
    static final int MAXIMUM_FAILURE_COUNT = ${profile.maximumFailureCount};
    static final int MAXIMUM_BACKOFF_EXPONENT = ${profile.maximumBackoffExponent};
    static final long MAXIMUM_BACKOFF_SECONDS = ${profile.maximumBackoffSeconds}L;
    static final long BACKOFF_JITTER_MS = ${profile.backoffJitterMs}L;

    private GeneratedRelayProfile() {}
}
`;

const outputs = [
  [resolve(root, "packages/rust/qc-relay-protocol/src/generated_profile.rs"), rust],
  [resolve(root, "apps/android/android/app/src/main/java/com/qccontrol/mobile/GeneratedRelayProfile.java"), java]
];
let stale = false;
for (const [path, content] of outputs) {
  if (process.argv.includes("--check")) {
    const current = await readFile(path, "utf8").catch(() => "");
    if (current.replaceAll("\r\n", "\n") !== content) {
      console.error(`${path} is not generated from contracts/qc-relay-profile.v1.json`);
      stale = true;
    }
  } else await writeFile(path, content);
}
if (stale) process.exitCode = 1;
