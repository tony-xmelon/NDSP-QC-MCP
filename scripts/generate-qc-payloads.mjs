import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = path.join(root, "contracts", "qc-payloads.v1.schema.json");
const schema = JSON.parse(fs.readFileSync(schemaPath, "utf8"));
const names = schema["x-generate"];
const rustNames = new Set(schema["x-rust-types"]);

const refName = value => value.$ref?.split("/").at(-1);
function tsType(value) {
  const nullable = value["x-nullable"] ? " | null" : "";
  if (refName(value)) return refName(value);
  if (value.enum) return value.enum.map(item => JSON.stringify(item)).join(" | ") + nullable;
  if (value.type === "object") return "Record<string, unknown>";
  if (value.type === "array") {
    const item = tsType(value.items);
    return `${item.includes(" | ") ? `(${item})` : item}[]`;
  }
  return ({ string: "string", integer: "number", number: "number", boolean: "boolean" }[value.type] ?? "unknown") + nullable;
}
function rustType(value) {
  if (value["x-rust-type"]) return value["x-rust-type"];
  if (refName(value)) return refName(value);
  if (value.enum) return "String";
  if (value.type === "object") return "serde_json::Value";
  if (value.type === "array") return `Vec<${rustType(value.items)}>`;
  return value["x-rust-type"] ?? { string: "String", integer: "u32", number: "f64", boolean: "bool" }[value.type];
}
function pythonType(value) {
  const base = refName(value) ? refName(value)
    : value.enum ? `Literal[${value.enum.map(item => JSON.stringify(item)).join(", ")}]`
    : value.type === "object" ? "dict[str, Any]"
    : value.type === "array" ? `list[${pythonType(value.items)}]`
    : ({ string: "str", integer: "int", number: "float", boolean: "bool" }[value.type] ?? "Any");
  return value["x-nullable"] ? `${base} | None` : base;
}
const snake = value => value.replace(/[A-Z]/g, match => `_${match.toLowerCase()}`);

let ts = "// Generated by scripts/generate-qc-payloads.mjs. Do not edit by hand.\n";
let rust = "// Generated by scripts/generate-qc-payloads.mjs. Do not edit by hand.\nuse serde::Serialize;\n\n";
let python = "# Generated by scripts/generate-qc-payloads.mjs. Do not edit by hand.\nfrom __future__ import annotations\nfrom typing import Any, Literal, NotRequired, TypedDict\n\n";
for (const name of names) {
  const definition = schema.$defs[name];
  const required = new Set(definition.required ?? []);
  ts += `\nexport interface ${name} {\n`;
  python += `\nclass ${name}(TypedDict):\n`;
  if (rustNames.has(name)) rust += `#[derive(Debug, Clone, PartialEq, Serialize)]\n#[serde(rename_all = "camelCase")]\npub struct ${name} {\n`;
  for (const [field, value] of Object.entries(definition.properties)) {
    const optional = !required.has(field);
    ts += `  ${field}${optional ? "?" : ""}: ${tsType(value)};\n`;
    python += `    ${field}: ${optional ? `NotRequired[${pythonType(value)}]` : pythonType(value)}\n`;
    if (rustNames.has(name)) {
      const rustField = field === "type" ? "r#type" : snake(field);
      if (optional) rust += "    #[serde(skip_serializing_if = \"Option::is_none\")]\n";
      rust += `    pub ${rustField}: ${optional || value["x-nullable"] ? `Option<${rustType(value)}>` : rustType(value)},\n`;
    }
  }
  ts += "}\n";
  if (Object.keys(definition.properties).length === 0) python += "    pass\n";
  if (rustNames.has(name)) rust += "}\n\n";
}

const outputs = new Map([
  [path.join(root, "packages", "typescript", "qc-client", "src", "generated-payloads.ts"), ts],
  [path.join(root, "packages", "rust", "qc-protocol", "src", "generated_payloads.rs"), rust],
  [path.join(root, "services", "device-gateway", "src", "qc_device_gateway", "generated_payloads.py"), python],
]);
let drift = false;
for (const [target, content] of outputs) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
  if (current === content) continue;
  if (process.argv.includes("--check")) { console.error(`Generated payload drift: ${path.relative(root, target)}`); drift = true; }
  else { fs.mkdirSync(path.dirname(target), { recursive: true }); fs.writeFileSync(target, content); }
}
if (drift) process.exit(1);
